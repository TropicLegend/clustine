//! Renders the game data as the committed output: Rust source and packed tables.
//!
//! Rust is laid out here, by hand, one entry per line, so that a version update is a
//! readable diff; it is never passed through a formatter, so its bytes do not depend on
//! a toolchain. The crates include it under `#[rustfmt::skip]`. What is thousands of
//! rows of one shape is packed instead (`tables.rs`). See
//! `docs/adr/0019-data-made-from-mojangs-jar.md`, sections 1 and 3.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail, ensure};

use crate::density;
use crate::item_defaults;
use crate::jar::SERVER_JAR;
use crate::model::{GameData, ItemComponents, Property};
use crate::worldgen::{NoiseParameters, NoiseSettings};
use crate::{carver, feature, material, packed, router, structure, sums, tables};

/// Directories that hold nothing but generated files, relative to the workspace root
/// (ADR-0019, section 3).
pub const DIRECTORIES: [&str; 4] = [DATA_DIR, PROTOCOL_DIR, WORLDGEN_DIR, REFERENCE_DIR];

const DATA_DIR: &str = "crates/clustine-data/src/generated";
const PROTOCOL_DIR: &str = "crates/clustine-protocol/src/generated";
const WORLDGEN_DIR: &str = "crates/clustine-worldgen-data/src/generated";
/// Values the game computes, for tests to compare with. No Rust is in it.
pub const REFERENCE_DIR: &str = "crates/clustine-worldgen-data/reference";

/// The noise settings whose routers are emitted: the three dimensions the plan builds
/// and no other preset (ADR-0019, section 1).
pub const DIMENSIONS: [&str; 3] = ["overworld", "nether", "end"];

const LINE_WIDTH: usize = 100;

/// The most that all committed generated output may come to, in bytes: the generated
/// directories and the sums (ADR-0019, section 6).
pub const TOTAL_BUDGET: usize = 6_000_000;

/// The most that the emitted code may come to, in bytes: the files whose form is
/// "code", which are the routers (ADR-0019, section 6; provisional there).
pub const CODE_BUDGET: usize = 1_000_000;

/// The second line of every file of emitted code (ADR-0019, section 8).
pub const EMITTER_LINE: &str = "// The emitter is adapted from SteelMC; see tools/datagen/NOTICE.";

/// Whether the generated file at `path` (from the workspace root, with `/`) has the
/// form "code": a noise router or a material rule. The splines and the other statics
/// beside them do not.
pub fn is_emitted_code(path: &str) -> bool {
    path.starts_with(WORLDGEN_DIR)
        && (path.ends_with("/router.rs") || path.ends_with("/material_rule.rs"))
}

/// Whether the generated file at `path` is written by the emitter that is adapted from
/// SteelMC, and says so in its second line: a noise router or its splines. The
/// material rules' emitter is Clustine's own.
#[cfg(test)]
pub fn is_from_the_adapted_emitter(path: &str) -> bool {
    path.starts_with(WORLDGEN_DIR)
        && (path.ends_with("/router.rs") || path.ends_with("/splines.rs"))
}

/// The file in each generated directory that says whose the data in it is. Packed
/// tables carry no comment, so the directory does.
pub const NOTICE_FILE: &str = "NOTICE";

/// The first line of every generated Rust file, for the game version `version`.
pub fn head(version: &str) -> String {
    format!(
        "// Generated by cargo datagen from Minecraft {version}. Do not edit. The data in this \
         file is Mojang's and not under the AGPL; the code around it is: see NOTICE.md."
    )
}

/// A generated file.
pub struct Output {
    /// Relative to the workspace root, with `/` between its parts.
    pub path: PathBuf,
    pub content: Vec<u8>,
}

/// Every committed output, the sums last. `root` is the workspace, whose files the
/// sums take the hashes of datagen's own inputs from.
pub fn all(data: &GameData, root: &Path) -> Result<Vec<Output>> {
    let mut outputs = generated(data)?;
    let sums = sums::render(
        SERVER_JAR.sha1,
        &sums::inputs(root)?,
        outputs
            .iter()
            .map(|output| (output.path.as_path(), output.content.as_slice())),
    )?;
    outputs.push(Output {
        path: PathBuf::from(sums::PATH),
        content: sums.into_bytes(),
    });
    check_budget(&outputs, TOTAL_BUDGET)?;
    check_code_budget(&outputs, CODE_BUDGET)?;
    Ok(outputs)
}

/// Fails if the emitted code among `outputs` comes to more than `budget` bytes.
pub fn check_code_budget(outputs: &[Output], budget: usize) -> Result<()> {
    let mut total = 0;
    for output in outputs {
        if is_emitted_code(&sums::slashed(&output.path)?) {
            total += output.content.len();
        }
    }
    ensure!(
        total <= budget,
        "the emitted code comes to {total} bytes, over the budget of {budget} \
         (docs/adr/0019-data-made-from-mojangs-jar.md, section 6)"
    );
    Ok(())
}

/// Fails if `outputs` come to more than `budget` bytes, so that nothing over budget is
/// ever written.
pub fn check_budget(outputs: &[Output], budget: usize) -> Result<()> {
    let total: usize = outputs.iter().map(|output| output.content.len()).sum();
    ensure!(
        total <= budget,
        "the generated output comes to {total} bytes, over the budget of {budget} \
         (docs/adr/0019-data-made-from-mojangs-jar.md, section 6)"
    );
    Ok(())
}

/// The files of the generated directories.
fn generated(data: &GameData) -> Result<Vec<Output>> {
    let mut outputs = Vec::new();
    let version = data.version.id.as_str();
    let mut add = |dir: &str, name: &str, body: String| {
        outputs.push(Output {
            path: PathBuf::from(dir).join(name),
            content: format!("{}\n\n{body}", head(version)).into_bytes(),
        });
    };

    add(
        DATA_DIR,
        "mod.rs",
        modules(&[
            "block_classes",
            "attributes",
            "block_physics",
            "block_properties",
            "blocks",
            "dimension_types",
            "entity_types",
            "item_components",
            "items",
            "loot_tables",
            "path_types",
            "registries",
            "sound_events",
            "sound_types",
            "spawning",
            "spawns",
            "tags",
            "trades",
            "version",
        ]),
    );
    add(DATA_DIR, "version.rs", version_file(data)?);
    add(DATA_DIR, "blocks.rs", blocks(data)?);
    add(DATA_DIR, "block_properties.rs", block_properties(data)?);
    add(DATA_DIR, "block_classes.rs", block_classes(data)?);
    add(DATA_DIR, "items.rs", items(data)?);
    add(DATA_DIR, "entity_types.rs", entity_types(data)?);
    add(DATA_DIR, "attributes.rs", attributes(data)?);
    add(DATA_DIR, "path_types.rs", path_types(data)?);
    add(DATA_DIR, "block_physics.rs", block_physics(data)?);
    add(DATA_DIR, "item_components.rs", item_components(data)?);
    add(DATA_DIR, "loot_tables.rs", loot_tables(data)?);
    add(DATA_DIR, "sound_events.rs", sound_events(data)?);
    let (types, of_states) = sound_types(data)?;
    add(DATA_DIR, "sound_types.rs", types);
    add(DATA_DIR, "registries.rs", registries(data));
    add(DATA_DIR, "dimension_types.rs", dimension_types(data));
    add(DATA_DIR, "tags.rs", tags(data));
    add(DATA_DIR, "trades.rs", crate::trades::emit(&data.trades)?);
    let biomes = data
        .synced_registries
        .iter()
        .find(|registry| registry.name == "worldgen/biome")
        .context("the registry of biomes is not among the synchronised ones")?;
    add(
        DATA_DIR,
        "spawning.rs",
        crate::spawning::emit(&data.extract)?,
    );
    add(
        DATA_DIR,
        "spawns.rs",
        crate::spawns::emit(&biomes.entries, &data.entity_types, &data.worldgen)?,
    );

    add(
        PROTOCOL_DIR,
        "mod.rs",
        modules(&["component_ids", "packet_ids"]),
    );
    add(
        PROTOCOL_DIR,
        "component_ids.rs",
        component_ids(&data.data_component_types, &data.potions, &data.mob_effects)?,
    );
    add(PROTOCOL_DIR, "packet_ids.rs", packet_ids(data)?);

    outputs.push(Output {
        path: PathBuf::from(DATA_DIR).join("state_sound_types.bin"),
        content: of_states,
    });
    outputs.push(Output {
        path: PathBuf::from(DATA_DIR).join("state_path_types.bin"),
        content: state_path_types(data)?,
    });
    outputs.push(Output {
        path: PathBuf::from(DATA_DIR).join("block_states.bin"),
        content: tables::block_states(
            &data.extract.states,
            &data.blocks,
            &data.block_tag("minecraft:blocks_motion_in_heightmap")?,
            &data.block_tag("minecraft:blocks_motion_in_heightmap_no_leaves")?,
            data.fluids.len(),
            SERVER_JAR.sha1,
        )
        .context("packing block_states.bin")?,
    });
    outputs.push(Output {
        path: PathBuf::from(DATA_DIR).join("collisions.bin"),
        content: tables::collisions(
            &data.extract.voxel_shapes,
            &data.extract.state_collisions,
            data.blocks.last().map_or(0, |block| block.last_state + 1),
            SERVER_JAR.sha1,
        )
        .context("packing collisions.bin")?,
    });
    outputs.push(Output {
        // ADR-0019 puts this table into the crate of world-generation data. It is
        // still beside the block states, where its reader is, and moves with it when
        // the biome source is built (the terrain plan's T3).
        path: PathBuf::from(DATA_DIR).join("biome_parameters.bin"),
        content: tables::biome_parameters(
            &data.extract.biome_parameters,
            &data.biome_reports,
            data.biomes()?,
            SERVER_JAR.sha1,
        )
        .context("packing biome_parameters.bin")?,
    });

    worldgen(data, &mut outputs)?;

    for directory in DIRECTORIES {
        let notice = notice(version, directory, &outputs);
        outputs.push(Output {
            path: PathBuf::from(directory).join(NOTICE_FILE),
            content: notice.into_bytes(),
        });
    }
    Ok(outputs)
}

/// The outputs of the crate of world-generation data: the routers of the three
/// dimensions with their splines, their material rules, the noises, the noise
/// settings, what the rules read of a biome, the carvers and which biome has which,
/// and the values the routers are tested against.
fn worldgen(data: &GameData, outputs: &mut Vec<Output>) -> Result<()> {
    let version = data.version.id.as_str();
    let mut add = |name: &str, emitted: bool, body: String| {
        let head = if emitted {
            format!("{}\n{EMITTER_LINE}", head(version))
        } else {
            head(version)
        };
        outputs.push(Output {
            path: PathBuf::from(WORLDGEN_DIR).join(name),
            content: format!("{head}\n\n{body}").into_bytes(),
        });
    };

    let registry = density::registry(data.worldgen.registry("density_function")?)?;
    let mut all_settings = Vec::new();
    for name in DIMENSIONS {
        let json = data
            .worldgen
            .entry("noise_settings", &format!("minecraft:{name}"))?;
        let settings = NoiseSettings::parse(json, &data.worldgen, &data.blocks)
            .with_context(|| format!("reading the noise settings {name}"))?;
        all_settings.push((name, settings));
    }

    let mut noises = BTreeMap::new();
    for (name, json) in data.worldgen.registry("noise")? {
        let parameters =
            NoiseParameters::parse(json).with_context(|| format!("reading the noise {name}"))?;
        noises.insert(name.clone(), parameters);
    }

    router::check_legacy_noises(&noises)?;

    let biomes = data
        .synced_registries
        .iter()
        .find(|registry| registry.name == "worldgen/biome")
        .context("the registry of biomes is not among the synchronised ones")?;
    let noise_names: Vec<String> = noises.keys().cloned().collect();
    let rules = material::Registries::load(&data.worldgen, &data.blocks)?;

    let mut top = vec![
        "biomes",
        "carvers",
        "features",
        "noise_settings",
        "noises",
        "spawn_search",
        "structures",
        "template_pools",
    ];
    top.extend(DIMENSIONS);
    top.sort_unstable();
    add("mod.rs", false, modules(&top));
    add(
        "biomes.rs",
        false,
        material::biomes(&biomes.entries, &data.worldgen)?,
    );
    add(
        "carvers.rs",
        false,
        carver::emit(&biomes.entries, &data.worldgen)?,
    );
    add(
        "features.rs",
        false,
        feature::emit(&biomes.entries, &data.worldgen, &data.extract.feature_order)?,
    );
    add("noises.rs", false, router::noises(&noises)?);
    add(
        "spawn_search.rs",
        false,
        spawn_search(&data.extract.spawn_rings)?,
    );
    let templates = structure::templates(&data.worldgen)?;
    add(
        "structures.rs",
        false,
        structure::structures(&data.worldgen, &biomes.entries, &data.tags)?,
    );
    add(
        "template_pools.rs",
        false,
        structure::template_pools(&data.worldgen, &templates)?,
    );
    let table =
        structure::templates_table(&templates, SERVER_JAR.sha1).context("packing templates.bin")?;
    let borrowed: Vec<(&str, &NoiseSettings)> = all_settings
        .iter()
        .map(|(name, settings)| (*name, settings))
        .collect();
    add(
        "noise_settings.rs",
        false,
        router::noise_settings(&borrowed)?,
    );

    for (name, settings) in &all_settings {
        let rule = material::emit(
            name,
            &settings.material_rule,
            &rules,
            &biomes.entries,
            &noise_names,
        )
        .with_context(|| format!("emitting the material rule of {name}"))?;
        let of_rule = router::Material {
            type_path: format!("super::material_rule::{}", rule.type_name),
            functions: rule.functions,
        };
        let emitted = router::emit(name, settings, &registry, &noises, &of_rule)
            .with_context(|| format!("emitting the noise router of {name}"))?;
        let mut inner = vec!["material_rule", "router"];
        if emitted.splines.is_some() {
            inner.push("splines");
        }
        add(&format!("{name}/mod.rs"), false, modules(&inner));
        add(&format!("{name}/material_rule.rs"), false, rule.text);
        add(&format!("{name}/router.rs"), true, emitted.router);
        if let Some(splines) = emitted.splines {
            add(&format!("{name}/splines.rs"), true, splines);
        }
    }

    outputs.push(Output {
        path: PathBuf::from(WORLDGEN_DIR).join("tables/templates.bin"),
        content: table,
    });

    // The values the game's own routers give: one file for each dimension and seed.
    let mut found = Vec::new();
    for (file, values) in &data.extract.router_values {
        let (name, settings) = all_settings
            .iter()
            .find(|(name, _)| values.settings == format!("minecraft:{name}"))
            .with_context(|| format!("the values {file} are of no dimension that is emitted"))?;
        ensure!(
            *file == format!("{name}_{}", values.seed),
            "the values {file} say that they are of {} and the seed {}",
            values.settings,
            values.seed
        );
        values.check_entries(settings.aquifers.is_some())?;
        found.push(*name);
        outputs.push(Output {
            path: PathBuf::from(REFERENCE_DIR).join(format!("router_{file}.txt")),
            content: values.render().into_bytes(),
        });
    }
    for name in DIMENSIONS {
        ensure!(
            found.contains(&name),
            "the extract program wrote no values of the router of {name}"
        );
    }
    Ok(())
}

/// `spawn_search.rs`: the passes of the game's search for a place to spawn.
fn spawn_search(passes: &[crate::extract::SpawnPass]) -> Result<String> {
    // The game's two passes, which the search is ported for: a change here is a
    // change of the game's search to be looked at, not data to pass through.
    let increments: Vec<u32> = passes.iter().map(|pass| pass.increment).collect();
    ensure!(
        increments == [512, 32],
        "the search for a spawn has passes of the increments {increments:?}, not 512 and 32"
    );
    let mut out = String::from(
        "use crate::density::SpawnPass;\n\n\
         /// The passes of `NoiseSpawnFinder.radialSearch`, in the game's order.\n",
    );
    writeln!(out, "pub static PASSES: [SpawnPass; {}] = [", passes.len())?;
    for pass in passes {
        writeln!(out, "    SpawnPass {{")?;
        writeln!(out, "        increment: {},", pass.increment)?;
        writeln!(out, "        offsets: &[")?;
        let mut line = String::new();
        for [x, z] in &pass.offsets {
            let item = format!("[{x}, {z}],");
            if !line.is_empty() && 12 + line.len() + 1 + item.len() > LINE_WIDTH {
                writeln!(out, "            {line}")?;
                line.clear();
            }
            if !line.is_empty() {
                line.push(' ');
            }
            line.push_str(&item);
        }
        if !line.is_empty() {
            writeln!(out, "            {line}")?;
        }
        writeln!(out, "        ],")?;
        writeln!(out, "    }},")?;
    }
    writeln!(out, "];")?;
    Ok(out)
}

/// The notice of a generated directory: whose the data is, and the files it covers.
fn notice(version: &str, directory: &str, outputs: &[Output]) -> String {
    let mut names: Vec<String> = outputs
        .iter()
        .filter_map(|output| output.path.strip_prefix(directory).ok())
        .map(|name| name.to_string_lossy().replace('\\', "/"))
        .collect();
    names.sort();
    // The directory of values to test against holds no file that could say it itself.
    let files = if names.iter().any(|name| name.ends_with(".txt")) {
        "The files, values to test against, which can carry no such line themselves:"
    } else {
        "The files, of which the packed tables (*.bin) can carry no such line themselves:"
    };
    let mut out = format!(
        "Generated by cargo datagen from Minecraft {version}. Do not edit. The data in the files\n\
         of this directory is Mojang's and not under the AGPL; the code around it is: see\n\
         NOTICE.md at the root of the repository.\n\n\
         {files}\n\n"
    );
    for name in names {
        out.push_str("  ");
        out.push_str(&name);
        out.push('\n');
    }
    out
}

fn modules(names: &[&str]) -> String {
    names
        .iter()
        .map(|name| format!("pub mod {name};\n"))
        .collect()
}

fn version_file(data: &GameData) -> Result<String> {
    let version = &data.version;
    let sha1 = packed::sha1_bytes(SERVER_JAR.sha1)?;
    let bytes: Vec<String> = sha1.iter().map(|byte| format!("0x{byte:02x}")).collect();
    Ok(format!(
        "pub const GAME_VERSION: &str = {:?};\n\
         pub const PROTOCOL_VERSION: i32 = {};\n\
         pub const DATA_VERSION: i32 = {};\n\
         \n\
         /// The server jar these tables are made from, as Mojang publishes it.\n\
         pub const SERVER_JAR_URL: &str = {:?};\n\
         pub const SERVER_JAR_SHA1: &str = {:?};\n\
         pub const SERVER_JAR_SHA1_BYTES: [u8; 20] = [\n    {},\n    {},\n];\n",
        version.id,
        version.protocol,
        version.data,
        SERVER_JAR.url,
        SERVER_JAR.sha1,
        bytes[..10].join(", "),
        bytes[10..].join(", "),
    ))
}

/// The properties of every block: the distinct properties, the distinct lists of them,
/// which list each block has, and the blocks sorted by name.
fn block_properties(data: &GameData) -> Result<String> {
    let distinct: BTreeSet<&Property> = data
        .blocks
        .iter()
        .flat_map(|block| &block.properties)
        .collect();
    let properties: Vec<&Property> = distinct.into_iter().collect();
    let number = |property: &Property| {
        properties
            .binary_search(&property)
            .map_err(|_| anyhow::anyhow!("a property went missing"))
    };

    let mut lists: BTreeSet<Vec<usize>> = BTreeSet::new();
    let mut of_block = Vec::new();
    for block in &data.blocks {
        let list = block
            .properties
            .iter()
            .map(number)
            .collect::<Result<Vec<_>>>()?;
        lists.insert(list.clone());
        of_block.push(list);
    }
    let lists: Vec<Vec<usize>> = lists.into_iter().collect();
    let block_lists = of_block
        .iter()
        .map(|list| {
            lists
                .binary_search(list)
                .map_err(|_| anyhow::anyhow!("a list went missing"))
        })
        .collect::<Result<Vec<_>>>()?;

    let mut by_name: Vec<usize> = (0..data.blocks.len()).collect();
    by_name.sort_by(|&a, &b| data.blocks[a].name.cmp(&data.blocks[b].name));
    ensure!(
        properties.len() <= usize::from(u16::MAX) && lists.len() <= usize::from(u16::MAX),
        "the properties no longer fit 16-bit numbers"
    );

    let mut out = String::new();
    writeln!(out, "use crate::BlockProperty;\n")?;
    writeln!(
        out,
        "/// Every distinct property, by name and then by its values."
    )?;
    writeln!(
        out,
        "pub static PROPERTIES: [BlockProperty; {}] = [",
        properties.len()
    )?;
    for property in &properties {
        let values: Vec<String> = property
            .values
            .iter()
            .map(|value| format!("{value:?}"))
            .collect();
        writeln!(
            out,
            "    BlockProperty {{ name: {:?}, values: &[{}] }},",
            property.name,
            values.join(", ")
        )?;
    }
    writeln!(out, "];\n")?;
    writeln!(
        out,
        "/// Every distinct list of properties a block has, as numbers in `PROPERTIES`. The game"
    )?;
    writeln!(
        out,
        "/// numbers the states of a block by them, the first counting most."
    )?;
    writeln!(
        out,
        "pub static PROPERTY_LISTS: [&[u16]; {}] = [",
        lists.len()
    )?;
    for list in &lists {
        let numbers: Vec<String> = list.iter().map(usize::to_string).collect();
        writeln!(out, "    &[{}],", numbers.join(", "))?;
    }
    writeln!(out, "];\n")?;
    writeln!(
        out,
        "/// Which of `PROPERTY_LISTS` each block has, by block id."
    )?;
    writeln!(
        out,
        "pub static BLOCK_PROPERTY_LISTS: [u16; {}] = [",
        block_lists.len()
    )?;
    out.push_str(&wrapped(&block_lists, "    "));
    writeln!(out, "];\n")?;
    writeln!(
        out,
        "/// The ids of the blocks in the order of their names, to find a block by its name."
    )?;
    writeln!(
        out,
        "pub static BLOCKS_BY_NAME: [u16; {}] = [",
        by_name.len()
    )?;
    out.push_str(&wrapped(&by_name, "    "));
    writeln!(out, "];")?;
    Ok(out)
}

/// What the game's code says of every block (ADR-0019, table 4), with the names of the
/// fluids and of the block entity types that the tables number.
fn block_classes(data: &GameData) -> Result<String> {
    let dumped = &data.extract.blocks;
    ensure!(
        dumped.len() == data.blocks.len(),
        "the extract program wrote {} blocks, the report has {}",
        dumped.len(),
        data.blocks.len()
    );
    // Every class a block is of or is made from, with the classes each is made from:
    // a class that no block has as its own (`DiodeBlock`) is known by its descendants.
    let mut made_from: BTreeMap<&str, &[String]> = BTreeMap::new();
    for block in dumped {
        let chain = &block.ancestors[..];
        let links = std::iter::once((block.class.as_str(), chain)).chain(
            chain
                .iter()
                .enumerate()
                .map(|(at, class)| (class.as_str(), &chain[at + 1..])),
        );
        for (class, above) in links {
            let earlier = made_from.insert(class, above);
            ensure!(
                earlier.is_none_or(|earlier| earlier == above),
                "the class {class} is made from two lists of classes"
            );
        }
    }
    for class in made_from.keys() {
        let valid = class.starts_with(|c: char| c.is_ascii_uppercase())
            && class.chars().all(|c| c.is_ascii_alphanumeric());
        ensure!(valid, "the class {class} cannot name a variant");
    }

    let mut out = String::new();
    writeln!(out, "use crate::BlockInfo;\n")?;
    writeln!(
        out,
        "/// The fluids by the game's ids, which a block state's row names its fluid by."
    )?;
    writeln!(out, "pub static FLUIDS: [&str; {}] = [", data.fluids.len())?;
    for name in &data.fluids {
        writeln!(out, "    {name:?},")?;
    }
    writeln!(out, "];\n")?;
    writeln!(
        out,
        "/// The explosion resistance of each fluid, by the game's ids (`getExplosionResistance`)."
    )?;
    writeln!(
        out,
        "pub static FLUID_EXPLOSION_RESISTANCE: [f32; {}] = [",
        data.extract.fluid_resistance.len()
    )?;
    for bits in &data.extract.fluid_resistance {
        writeln!(out, "    f32::from_bits({bits:#010x}),")?;
    }
    writeln!(out, "];\n")?;
    writeln!(out, "/// The block entity types by the game's ids.")?;
    writeln!(
        out,
        "pub static BLOCK_ENTITY_TYPES: [&str; {}] = [",
        data.block_entity_types.len()
    )?;
    for name in &data.block_entity_types {
        writeln!(out, "    {name:?},")?;
    }
    writeln!(out, "];\n")?;

    writeln!(
        out,
        "/// The classes of the game's blocks, by the simple names of the Java classes."
    )?;
    writeln!(
        out,
        "#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]"
    )?;
    writeln!(out, "pub enum BlockClass {{")?;
    for class in made_from.keys() {
        writeln!(out, "    {class},")?;
    }
    writeln!(out, "}}\n")?;
    writeln!(out, "impl BlockClass {{")?;
    writeln!(
        out,
        "    /// The classes this one is made from, nearest first, without the base of all\n    \
         /// blocks."
    )?;
    writeln!(
        out,
        "    pub fn ancestors(self) -> &'static [BlockClass] {{"
    )?;
    writeln!(out, "        ANCESTORS[self as usize]")?;
    writeln!(out, "    }}")?;
    writeln!(out, "}}\n")?;
    writeln!(
        out,
        "/// What [`BlockClass::ancestors`] gives, in the order of the classes."
    )?;
    writeln!(
        out,
        "static ANCESTORS: [&[BlockClass]; {}] = [",
        made_from.len()
    )?;
    for (class, above) in &made_from {
        let listed: Vec<String> = above
            .iter()
            .map(|name| format!("BlockClass::{name}"))
            .collect();
        writeln!(out, "    &[{}], // {class}", listed.join(", "))?;
    }
    writeln!(out, "];\n")?;
    writeln!(
        out,
        "// The table names the classes without their type, which its lines would repeat."
    )?;
    writeln!(out, "use self::BlockClass::*;\n")?;
    writeln!(
        out,
        "/// What the game's code says of each block, by block id."
    )?;
    writeln!(
        out,
        "pub static BLOCK_INFO: [BlockInfo; {}] = [",
        dumped.len()
    )?;
    for (block, dumped) in data.blocks.iter().zip(dumped) {
        ensure!(
            block.name == dumped.name,
            "the extract program has {} where the report has {}",
            dumped.name,
            block.name
        );
        let entity_type = match dumped.block_entity_type {
            Some(id) => {
                ensure!(
                    id < data.block_entity_types.len() && id <= usize::from(u8::MAX),
                    "{} has the block entity type {id}, which the registry lacks",
                    block.name
                );
                format!("Some({id})")
            }
            None => "None".to_owned(),
        };
        let potted = match dumped.potted {
            Some(id) => {
                ensure!(
                    id < data.blocks.len(),
                    "{} holds the block {id}, which the report lacks",
                    block.name
                );
                format!("Some({id})")
            }
            None => "None".to_owned(),
        };
        let name = block.name.strip_prefix("minecraft:").unwrap_or(&block.name);
        writeln!(
            out,
            "    BlockInfo {{ class: {}, block_entity_type: {entity_type}, \
             used_by_click: {}, survival_rule: {}, potted: {potted} }}, // {name}",
            dumped.class, dumped.used_by_click, dumped.survival_rule
        )?;
    }
    writeln!(out, "];")?;
    Ok(out)
}

