fn tags(data: &GameData) -> String {
    let mut out = String::from("use crate::{RegistryTags, Tag};\n\n");
    out.push_str(&format!(
        "pub static TAGS: [RegistryTags; {}] = [\n",
        data.tags.len()
    ));
    for registry in &data.tags {
        out.push_str("    RegistryTags {\n");
        out.push_str(&format!(
            "        registry: \"minecraft:{}\",\n",
            registry.registry
        ));
        out.push_str("        tags: &[\n");
        for tag in &registry.tags {
            out.push_str("            Tag {\n");
            out.push_str(&format!("                name: {:?},\n", tag.name));
            if tag.entries.is_empty() {
                out.push_str("                entries: &[],\n");
            } else {
                out.push_str("                entries: &[\n");
                out.push_str(&wrapped(&tag.entries, "                    "));
                out.push_str("                ],\n");
            }
            out.push_str("            },\n");
        }
        out.push_str("        ],\n    },\n");
    }
    out.push_str("];\n");
    out
}

fn packet_ids(data: &GameData) -> Result<String> {
    let mut out = String::new();
    let mut open_state = None;
    for set in &data.packets {
        if open_state != Some(set.state) {
            if open_state.is_some() {
                out.push_str("}\n\n");
            }
            writeln!(out, "pub mod {} {{", set.state)?;
            open_state = Some(set.state);
        } else {
            out.push('\n');
        }
        writeln!(out, "    pub mod {} {{", set.direction)?;
        for (id, name) in set.packets.iter().enumerate() {
            let constant = constant_name(name)?;
            ensure!(
                constant != "NAMES",
                "packet {name} collides with the NAMES table"
            );
            writeln!(out, "        pub const {constant}: i32 = {id};")?;
        }
        writeln!(
            out,
            "\n        pub static NAMES: [&str; {}] = [",
            set.packets.len()
        )?;
        for name in &set.packets {
            writeln!(out, "            {name:?},")?;
        }
        out.push_str("        ];\n    }\n");
    }
    if open_state.is_some() {
        out.push_str("}\n");
    }
    Ok(out)
}

/// The kinds of item component Clustine reads (`docs/groundwork/n9-plan.md`, section
/// 3.1), in the order of the world's `components::Kind`, each given a constant with its
/// id.
const COMPONENT_KINDS: [&str; 15] = [
    "minecraft:potion_contents",
    "minecraft:potion_duration_scale",
    "minecraft:charged_projectiles",
    "minecraft:enchantments",
    "minecraft:use_cooldown",
    "minecraft:fireworks",
    "minecraft:damage",
    "minecraft:intangible_projectile",
    "minecraft:banner_patterns",
    "minecraft:item_name",
    "minecraft:rarity",
    "minecraft:tooltip_display",
    "minecraft:suspicious_stew_effects",
    "minecraft:ominous_bottle_amplifier",
    "minecraft:chicken/variant",
];

/// The numbers the wire gives item components and the registry values in them: the
/// ids of the kinds Clustine reads, and the names of every kind, potion and mob effect
/// by id, which the edge turns the world's names into and back.
fn component_ids(types: &[String], potions: &[String], effects: &[String]) -> Result<String> {
    let mut out = String::from("pub mod data_component_type {\n");
    for kind in COMPONENT_KINDS {
        let id = types
            .iter()
            .position(|name| name == kind)
            .with_context(|| format!("registries.json has no item component {kind}"))?;
        let constant = constant_name(kind)?;
        ensure!(
            constant != "NAMES",
            "the item component {kind} collides with the NAMES table"
        );
        writeln!(out, "    pub const {constant}: i32 = {id};")?;
    }
    out.push('\n');
    names_table(&mut out, types)?;
    out.push_str("}\n");
    for (module, names) in [("potion", potions), ("mob_effect", effects)] {
        writeln!(out, "\npub mod {module} {{")?;
        names_table(&mut out, names)?;
        out.push_str("}\n");
    }
    Ok(out)
}

/// `pub static NAMES`, indented for a module, with `names` by id.
fn names_table(out: &mut String, names: &[String]) -> Result<()> {
    writeln!(out, "    pub static NAMES: [&str; {}] = [", names.len())?;
    for name in names {
        writeln!(out, "        {name:?},")?;
    }
    out.push_str("    ];\n");
    Ok(())
}

/// `minecraft:grass_block` becomes `GRASS_BLOCK`, `minecraft:debug/event` becomes `DEBUG_EVENT`.
fn constant_name(identifier: &str) -> Result<String> {
    let name = identifier.strip_prefix("minecraft:").unwrap_or(identifier);
    let name = name.replace('/', "_");
    let valid = name.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    ensure!(valid, "{identifier} cannot be turned into a constant name");
    Ok(name.to_ascii_uppercase())
}

/// Comma-separated numbers, wrapped to the line width, each line starting with `indent`.
pub(crate) fn wrapped(numbers: &[usize], indent: &str) -> String {
    let mut out = String::new();
    let mut line = String::new();
    for number in numbers {
        let item = format!("{number},");
        if !line.is_empty() && indent.len() + line.len() + 1 + item.len() > LINE_WIDTH {
            out.push_str(indent);
            out.push_str(&line);
            out.push('\n');
            line.clear();
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(&item);
    }
    if !line.is_empty() {
        out.push_str(indent);
        out.push_str(&line);
        out.push('\n');
    }
    out
}

